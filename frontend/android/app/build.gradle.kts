    targetCompatibility = JavaVersion.VERSION_17
    isCoreLibraryDesugaringEnabled = true
  }

    defaultConfig {
        applicationId = "com.lullabyte.lullabyte"
        // Explicit minSdk 23 (Android 6.0): required by firebase_auth /
